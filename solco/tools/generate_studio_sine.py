"""Generate the original, periodic lookup used only during sample-bank preparation."""
import math
from pathlib import Path
path=Path(__file__).resolve().parents[1]/'main/studio_sine.h'
values=[format(math.sin(2*math.pi*i/1024),'.9e')+'f' for i in range(1025)]
path.write_text('/* Generated by tools/generate_studio_sine.py; one original sine period. */\n#ifndef STUDIO_SINE_H\n#define STUDIO_SINE_H\nstatic const float s_studio_sine[1025] = {\n'+''.join('    '+', '.join(values[i:i+6])+',\n' for i in range(0,len(values),6))+'};\n#endif\n',encoding='utf-8')
