"""Generate sentinel/main/oui_table.c from Wireshark's "manuf" file.

The manuf file is derived from the IEEE MA-L registry. Download it from
https://www.wireshark.org/download/automated/data/manuf.gz, decompress it and run:

    python sentinel/tools/make_oui.py manuf sentinel/main/oui_table.c

Only 24-bit (MA-L) assignments are kept: sorted OUIs plus a deduplicated
vendor-name pool, searched with a binary search on the device.
"""
import re
import sys
from datetime import date
from pathlib import Path

# Legal suffixes removed from vendor names so they fit a watch row.
SUFFIXES = re.compile(
    r"[ ,.]*\b(inc|incorporated|corp|corporation|co|ltd|limited|llc|gmbh|ag|sa|s\.a|s\.p\.a|spa|srl|"
    r"bv|b\.v|ab|oy|as|a/s|plc|pte|pty|kg|nv|sas|kk|k\.k|company|technologies|technology|"
    r"electronics|electronic|international|holdings|group|eood|ood|corporate|trading)\b[ ,.]*$",
    re.IGNORECASE,
)
MAX_NAME = 28


def clean(name):
    name = re.sub(r"\s+", " ", name.replace("，", ",")).strip()
    for _ in range(4):
        shorter = SUFFIXES.sub("", name).strip(" ,.")
        if not shorter or shorter == name:
            break
        name = shorter
    name = name.encode("ascii", "ignore").decode()
    return name[:MAX_NAME].strip() or "?"


def main(source, output):
    entries = {}
    for line in Path(source).read_text(encoding="utf-8", errors="replace").splitlines():
        if not line or line.startswith("#"):
            continue
        fields = line.split("\t")
        prefix = fields[0].strip()
        if not re.fullmatch(r"[0-9A-Fa-f]{2}:[0-9A-Fa-f]{2}:[0-9A-Fa-f]{2}", prefix):
            continue  # MA-M / MA-S (/28, /36) blocks and malformed lines
        long_name = fields[2].strip() if len(fields) > 2 and fields[2].strip() else fields[1].strip()
        entries[int(prefix.replace(":", ""), 16)] = clean(long_name)
    names = sorted(set(entries.values()))
    index = {name: i for i, name in enumerate(names)}
    if len(names) >= 65536:
        raise SystemExit("too many vendor names for uint16_t indices")
    offsets, pool = [], bytearray()
    for name in names:
        offsets.append(len(pool))
        pool += name.encode() + b"\0"
    keys = sorted(entries)
    out = [
        "/* GENERATED by sentinel/tools/make_oui.py from Wireshark's manuf (IEEE MA-L).",
        f" * {len(keys)} OUIs, {len(names)} vendors, generated {date.today().isoformat()}. Do not edit. */",
        '#include "oui.h"',
        "#include <stddef.h>",
        "",
        f"static const uint8_t s_oui[{len(keys)}][3] = {{",
    ]
    for i in range(0, len(keys), 8):
        chunk = keys[i:i + 8]
        out.append("    " + ",".join("{0x%02x,0x%02x,0x%02x}" % (k >> 16, (k >> 8) & 255, k & 255) for k in chunk) + ",")
    out.append("};")
    out.append(f"static const uint16_t s_vendor[{len(keys)}] = {{")
    for i in range(0, len(keys), 16):
        out.append("    " + ",".join(str(index[entries[k]]) for k in keys[i:i + 16]) + ",")
    out.append("};")
    out.append(f"static const uint32_t s_offset[{len(names)}] = {{")
    for i in range(0, len(offsets), 12):
        out.append("    " + ",".join(str(o) for o in offsets[i:i + 12]) + ",")
    out.append("};")
    out.append("static const char s_names[] =")
    text = pool.decode()
    for i in range(0, len(text), 96):
        piece = text[i:i + 96].replace("\\", "\\\\").replace('"', '\\"').replace("\0", "\\000")
        out.append('    "' + piece + '"')
    out[-1] += ";"
    out += [
        "",
        "const char *sn_oui_vendor(const uint8_t mac[3])",
        "{",
        "    size_t low = 0, high = sizeof(s_oui) / sizeof(s_oui[0]);",
        "    uint32_t key = (uint32_t)mac[0] << 16 | (uint32_t)mac[1] << 8 | mac[2];",
        "    while (low < high)",
        "    {",
        "        size_t middle = (low + high) / 2;",
        "        uint32_t value = (uint32_t)s_oui[middle][0] << 16 | (uint32_t)s_oui[middle][1] << 8 | s_oui[middle][2];",
        "        if (value == key) return s_names + s_offset[s_vendor[middle]];",
        "        if (value < key) low = middle + 1;",
        "        else high = middle;",
        "    }",
        "    return NULL;",
        "}",
        "",
    ]
    Path(output).write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"{len(keys)} OUIs, {len(names)} vendors, pool {len(pool)} bytes, "
          f"~{len(keys) * 5 + len(names) * 4 + len(pool)} bytes of flash")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    main(sys.argv[1], sys.argv[2])
