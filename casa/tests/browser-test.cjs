const {chromium}=require('playwright');
const assert=require('assert/strict');
const path=require('path');
const fixture=require('./fixtures.cjs');
(async()=>{
  await fetch('http://127.0.0.1:8769/casa/api/config',{method:'DELETE'});
  const output=process.env.CASA_QA_OUTPUT||require('os').tmpdir();
  const browser=await chromium.launch({...(process.env.CASA_QA_BROWSER?{executablePath:process.env.CASA_QA_BROWSER}:{}),headless:true});
  try{
    const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    await page.addInitScript(()=>localStorage.setItem('appkit-token-'+location.host,'qa-browser-token'));
    await page.routeWebSocket('wss://casa-qa.example.test/api/websocket',socket=>{
      socket.send(JSON.stringify({type:'auth_required',ha_version:'QA-2026'}));
      socket.onMessage(data=>{const message=JSON.parse(data);if(message.type==='auth')return socket.send(JSON.stringify({type:message.access_token==='casa-qa-token'?'auth_ok':'auth_invalid',ha_version:'QA-2026'}));try{socket.send(JSON.stringify({id:message.id,type:'result',success:true,result:fixture.reply(message)}));}catch(error){socket.send(JSON.stringify({id:message.id,type:'result',success:false,error:{message:error.message}}));}});
    });
    await page.goto('http://127.0.0.1:8769/casa/');
    await page.locator('#setup:not(.hidden)').waitFor();
    await page.locator('#ha-url').fill('https://casa-qa.example.test');
    await page.locator('#ha-token').fill('casa-qa-token');
    await page.locator('#import').click();
    await page.waitForFunction(()=>document.querySelector('#import-message').textContent.includes('10 entità trovate'));
    assert.equal(await page.locator('.pick-row').count(),10);
    assert.equal(await page.locator('#picker img').count(),0,'Imported entity labels must remain text');
    await page.locator('#save').click();
    await page.waitForFunction(()=>document.querySelector('#feedback').textContent.includes('Configurazione salvata'));
    const report=await(await page.request.get('http://127.0.0.1:8769/qa')).json();
    const entities=report.lastSave.favorites;
    assert(entities.some(entity=>entity.id.length===255),'Long Home Assistant IDs must survive import unchanged');
    assert.equal(entities.find(e=>e.id==='sensor.living_temperature').area,'Soggiorno');
    assert.equal(entities.find(e=>e.id==='light.kitchen').area,'Cucina','Entity area overrides device area');
    assert(entities.find(e=>e.id==='light.kitchen').dashboards.includes('Piano terra / Cucina'),'Area cards contribute their entities');
    assert(entities.find(e=>e.id==='climate.living').dashboards.includes('Panoramica / Casa'),'Nested cards contribute entities');
    assert.equal(await page.locator('#ha-token').inputValue(),'');
    assert.equal(await page.evaluate(()=>Object.values(localStorage).some(value=>value.includes('casa-qa-token'))),false);
    await page.locator('#setup-toggle').click();
    await page.locator('[data-mode=category]').click();
    await page.locator('#group').selectOption({label:'Termometri'});
    assert.equal(await page.locator('#cards .entity').count(),1);
    await page.locator('#group').selectOption({label:'Prese'});
    assert.equal(await page.locator('#cards .entity').count(),1);
    await page.locator('[data-mode=dashboards]').click();
    await page.locator('#group').selectOption({label:'Piano terra / Cucina'});
    assert.equal(await page.locator('#cards .entity').count(),1);
    await page.locator('[data-mode=all]').click();
    await page.locator('#search').fill('light.kitchen');
    await page.getByRole('button',{name:'Accendi',exact:true}).click();
    let actions=(await(await page.request.get('http://127.0.0.1:8769/qa')).json()).actions;
    assert.equal(actions.at(-1).id,'light.kitchen');
    await page.locator('#cards input[type=range]').evaluate(input=>{input.value='66';input.dispatchEvent(new Event('change'));});
    await page.waitForTimeout(300);
    actions=(await(await page.request.get('http://127.0.0.1:8769/qa')).json()).actions;
    assert.deepEqual(actions.at(-1),{id:'light.kitchen',service:'turn_on',data:{brightness_pct:66}});
    await page.locator('#search').fill('');
    await page.screenshot({path:path.join(output,'casa-dashboard-desktop.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(output,'casa-dashboard-mobile.png'),fullPage:true});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile page must not scroll horizontally');
    await page.request.post('http://127.0.0.1:8769/qa',{data:{connected:false}});
    await page.evaluate(()=>loadState());
    assert.equal(await page.locator('#cards button:enabled').count(),0);
    assert.equal(await page.locator('#cards img').count(),0);
    await page.locator('#setup-toggle').click();
    page.once('dialog',dialog=>dialog.accept());
    await page.locator('#disconnect').click();
    await page.waitForFunction(()=>document.querySelector('#feedback').textContent.includes('Collegamento rimosso'));
    assert.equal((await(await page.request.get('http://127.0.0.1:8769/casa/api/config')).json()).has_token,false);
    assert.deepEqual(errors,[]);
    console.log('CASA_BROWSER_QA_PASS: remote WSS import, area inheritance, nested dashboards, types, actions, offline controls, escaping, mobile layout');
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
