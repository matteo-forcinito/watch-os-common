const {chromium}=require('playwright');
const assert=require('assert/strict'),path=require('path');
const base='http://127.0.0.1:8769';
(async()=>{
  await fetch(base+'/casa/api/config',{method:'DELETE'});
  await fetch(base+'/qa/extras',{method:'POST'});
  const catalog=(await(await fetch(base+'/casa/api/catalog',{method:'POST',body:JSON.stringify({type:'catalog',page:0})})).json());
  assert(catalog.ok);
  const read=async page=>{await fetch(base+'/casa/api/catalog',{method:'POST',body:JSON.stringify({type:'catalog',page})});return JSON.parse((await(await fetch(base+'/casa/api/catalog?job=1')).json()).response.event.result);};
  const all=[...(await read(0)).entities,...(await read(1)).entities];
  await fetch(base+'/casa/api/config',{method:'POST',body:JSON.stringify({url:'https://casa-qa.example.test',token:'casa-qa-token',favorites:all})});
  const browser=await chromium.launch({headless:true,...(process.env.CASA_QA_BROWSER?{executablePath:process.env.CASA_QA_BROWSER}:{})});
  try{
    const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    await page.addInitScript(()=>localStorage.setItem('appkit-token-'+location.host,'qa-browser-token'));
    // Reimport must use the panel and never open a browser HA connection.
    page.on('websocket',()=>{throw new Error('Saved credentials must stay on the panel');});
    await page.goto(base+'/casa/');
    await page.locator('#quick-grid .quick-card').first().waitFor();
    assert.equal(await page.locator('#quick-grid .quick-card').count(),4);
    assert.equal(await page.locator('#cards:visible').count(),0,'Catalog is below the landing page gesture');
    assert.deepEqual(await page.locator('#quick-grid strong').allTextContents(),['Alarmo','Temperatura','Termostato','Consumi']);
    await page.evaluate(()=>{const alarm=state.entities.find(e=>e.id==='alarm_control_panel.alarmo');state.entities.unshift({...alarm,id:'alarm_control_panel.panel',name:'Other panel'});updatePanel();});
    await page.getByRole('button',{name:'Apri menu Alarmo'}).click();
    assert((await page.locator('#alarm-controls').textContent()).includes('Alarmo'),'The quick menu must prefer Alarmo over another alarm panel');
    assert(!(await page.locator('#alarm-controls').textContent()).includes('Other panel'));
    await page.locator('#alarm-close').click();
    await page.evaluate(()=>loadState());
    await page.locator('#panel-home').evaluate(element=>{
      element.dispatchEvent(new PointerEvent('pointerdown',{pointerType:'touch',clientX:200,clientY:350,bubbles:true}));
      element.dispatchEvent(new PointerEvent('pointerup',{pointerType:'touch',clientX:200,clientY:100,bubbles:true}));
    });
    await page.locator('.priority-grid').waitFor();
    assert.equal(await page.locator('.all-devices>article').count(),6);
    assert.equal(await page.locator('.priority-grid .kind-alarm_control_panel').count(),1);
    assert.equal(await page.locator('.priority-grid .motion-card').count(),1);
    assert((await page.locator('.priority-grid .energy-card').textContent()).includes('230 V'));
    assert.equal(await page.locator('.priority-grid .energy-card .unit-metric').count(),3);
    const firstPage=await page.locator('.all-devices').textContent();
    await page.getByRole('button',{name:'Successivi',exact:true}).click();
    assert.notEqual(await page.locator('.all-devices').textContent(),firstPage);
    assert.equal(await page.locator('.all-devices>article').count(),6);
    await page.getByRole('button',{name:'Precedenti',exact:true}).click();
    const alarm=page.locator('.priority-grid .kind-alarm_control_panel');
    let before=(await(await page.request.get(base+'/qa')).json()).actions.length;
    page.once('dialog',d=>d.dismiss());await alarm.getByRole('button',{name:'Inserisci fuori casa',exact:true}).click();
    assert.equal((await(await page.request.get(base+'/qa')).json()).actions.length,before,'Cancel PIN must send no command');
    page.once('dialog',d=>d.accept('1234'));await alarm.getByRole('button',{name:'Inserisci fuori casa',exact:true}).click();
    await page.waitForTimeout(100);
    let actions=(await(await page.request.get(base+'/qa')).json()).actions;
    assert.deepEqual(actions.at(-1),{id:'alarm_control_panel.alarmo',service:'alarm_arm_away',data:{code:'1234'}});
    await page.request.post(base+'/qa',{data:{state:{id:'alarm_control_panel.alarmo',value:'armed_away'}}});await page.evaluate(()=>loadState());
    page.once('dialog',d=>d.accept('5678'));await alarm.getByRole('button',{name:'Disinserisci',exact:true}).click();
    await page.waitForTimeout(100);actions=(await(await page.request.get(base+'/qa')).json()).actions;
    assert.deepEqual(actions.at(-1),{id:'alarm_control_panel.alarmo',service:'alarm_disarm',data:{code:'5678'}});
    assert.equal(await alarm.locator('select option[value=alarm_arm_vacation]').count(),0,'Unsupported alarm modes are hidden');
    await page.locator('#setup-toggle').click();
    await page.locator('#home-choice').selectOption('1');await page.locator('#save-home').click();
    assert.equal((await(await page.request.get(base+'/casa/api/config')).json()).homepage,1);
    assert.equal(await page.locator('#ha-token').inputValue(),'');
    await page.locator('#import').click();
    await page.waitForFunction(()=>document.querySelector('#import-message').textContent.includes('80 entità trovate'));
    assert.equal(await page.locator('#picker .pick-row').count(),80);
    assert((await page.locator('#selected-count').textContent()).startsWith('80 /'),'Saved reimport preserves selection');
    assert.equal(await page.locator('#ha-token').inputValue(),'');
    const savedCatalog=await(await page.request.get(base+'/casa/api/catalog/cache')).json();
    assert.equal(savedCatalog.entities.length,80,'Reimport overwrites the persistent catalog');
    const indoor=page.locator('#indoor-picker input').first();
    await indoor.uncheck();await page.locator('#save').click();
    await page.waitForFunction(()=>!document.querySelector('#save').disabled);
    assert((await(await page.request.get(base+'/casa/api/config')).json()).favorites.some(e=>e.indoor===false),'Indoor overrides are persisted separately');
    let reads=0;
    page.on('request',request=>{if(new URL(request.url()).pathname==='/casa/api/catalog')reads++;});
    await page.reload();await page.locator('#quick-grid .quick-card').first().waitFor({state:'attached'});
    await page.locator('#setup-toggle').click();
    await page.locator('#picker .pick-row').first().waitFor();
    assert.equal(await page.locator('#picker .pick-row').count(),80,'Reopening restores the full cached catalog');
    assert.equal(await page.locator('#indoor-picker input').first().isChecked(),false,'Indoor overrides survive catalog restoration');
    assert.equal(reads,0,'Opening does not retrieve the HA catalog again');
    await page.locator('#setup-toggle').click();
    await page.locator('[data-mode=all]').click();
    assert.equal(await page.evaluate(()=>Object.values(localStorage).some(s=>s.includes('1234')||s.includes('casa-qa-token'))),false);
    await page.request.post(base+'/qa',{data:{state:{id:'climate.living',value:'unavailable'}}});await page.evaluate(()=>loadState());
    assert(!(await page.locator('.priority-grid .kind-climate .value').textContent()).includes('Spento'),'An unavailable thermostat must not be labelled off');
    await page.request.post(base+'/qa',{data:{state:{id:'climate.living',value:'heat'}}});await page.evaluate(()=>loadState());
    await page.locator('.priority-grid .climate-open').click();
    await page.setViewportSize({width:480,height:480});
    const dialog=page.locator('#climate-dialog');assert(await dialog.isVisible());
    assert(await dialog.evaluate(e=>e.scrollHeight<=e.clientHeight+1),JSON.stringify(await dialog.evaluate(e=>({scroll:e.scrollHeight,client:e.clientHeight,box:e.getBoundingClientRect().toJSON(),screen:e.firstElementChild.getBoundingClientRect().toJSON()}))));
    assert.equal(await page.locator('#climate-modes button').count(),3);
    const endpoints=await page.locator('#climate-track').evaluate(path=>{const matrix=path.getScreenCTM(),first=path.getPointAtLength(0).matrixTransform(matrix),last=path.getPointAtLength(path.getTotalLength()).matrixTransform(matrix);return {first:first.x,last:last.x,right:document.querySelector('.climate-screen').getBoundingClientRect().right};});
    assert(Math.abs(endpoints.first-endpoints.right)<2&&Math.abs(endpoints.last-endpoints.right)<2,'Both thermostat arc ends meet the right screen edge');
    assert((await page.locator('#climate-ambient').textContent()).includes('56 %'));
    await page.evaluate(()=>{const e=state.entities.find(e=>e.id==='climate.living');e.area='Senza stanza';e.current_temp=null;refreshClimate();});
    assert.equal(await page.locator('#climate-ambient').textContent(),'Ambiente —','Unassigned sensors must not be combined into a room measurement');
    await page.evaluate(()=>loadState());
    await page.locator('#climate-plus').click();await page.waitForTimeout(100);
    actions=(await(await page.request.get(base+'/qa')).json()).actions;
    assert.deepEqual(actions.at(-1),{id:'climate.living',service:'set_temperature',data:{temperature:22.5}});
    await page.screenshot({path:path.join(process.env.CASA_QA_OUTPUT||require('os').tmpdir(),'casa-thermostat-fullscreen.png')});
    await page.locator('#climate-close').click();
    await page.setViewportSize({width:390,height:844});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    assert.deepEqual(errors,[]);
    console.log('CASA_HOME_QA_PASS: saved credential reimport (80 entities, 2 batches), selection, bounded pagination, Alarmo PIN/actions/modes, energy metrics, full-screen thermostat');
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
